export function normalize(value={}) {
  const clamp=(v,min,max,fallback)=>typeof v==='number'&&Number.isFinite(v)?Math.min(max,Math.max(min,v)):fallback;
  return {
    volume:clamp(value.volume,0,150,100),
    bass:clamp(value.bass,-12,12,0),
    treble:clamp(value.treble,-12,12,0),
    balance:clamp(value.balance,-1,1,0),
    enabled:typeof value.enabled==='boolean'?value.enabled:true,
    bands:FREQUENCIES.map((_,i)=>clamp(value.bands?.[i],-12,12,0))
  };
}
